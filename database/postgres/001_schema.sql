-- PostgreSQL baseline equivalent to SQLite migrations 001–019.
-- Keep dates and JSON as text to preserve the existing API and imported values.

CREATE TABLE users (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username         TEXT UNIQUE,
  password_hash    TEXT,
  google_sub       TEXT UNIQUE,
  google_email     TEXT,
  guardian_contact TEXT,               -- SĐT hoặc email phụ huynh đã xác minh OTP
  guardian_type    TEXT CHECK (guardian_type IN ('phone', 'email')),
  nickname         TEXT,
  avatar           TEXT NOT NULL DEFAULT 'meo',
  avatar_frame     TEXT,               -- slug khung avatar đang dùng
  brush_skin       TEXT,               -- slug skin cọ đang dùng
  language         TEXT NOT NULL DEFAULT 'vi',
  role             TEXT NOT NULL DEFAULT 'user',
  friend_code      TEXT NOT NULL UNIQUE,
  rank_points      BIGINT NOT NULL DEFAULT 0,
  gacha_points     BIGINT NOT NULL DEFAULT 0,
  ruby             BIGINT NOT NULL DEFAULT 0,
  level            BIGINT NOT NULL DEFAULT 1,
  level_baseline   TEXT NOT NULL DEFAULT '{}',
  login_streak     BIGINT NOT NULL DEFAULT 0,
  last_login_date  TEXT,
  created_at       TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
, signature TEXT);

CREATE TABLE otp_codes (
  id          TEXT PRIMARY KEY,
  purpose     TEXT NOT NULL,           -- register | reset
  target      TEXT NOT NULL,
  code_hash   TEXT NOT NULL,
  payload     TEXT NOT NULL DEFAULT '{}',
  attempts    BIGINT NOT NULL DEFAULT 0,
  used        BIGINT NOT NULL DEFAULT 0,
  expires_at  TEXT NOT NULL,
  created_at  TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);

CREATE TABLE themes (
  id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug     TEXT NOT NULL UNIQUE,
  name_vi  TEXT NOT NULL,
  name_en  TEXT NOT NULL,
  sort     BIGINT NOT NULL DEFAULT 0
, active BIGINT NOT NULL DEFAULT 1, age_group TEXT NOT NULL DEFAULT '6+');

CREATE TABLE missions (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  level       BIGINT NOT NULL,
  idx         BIGINT NOT NULL,
  type        TEXT NOT NULL,
  target      BIGINT NOT NULL DEFAULT 1,
  param       TEXT,
  difficulty  TEXT NOT NULL CHECK (difficulty IN ('easy', 'medium', 'hard')),
  ruby        BIGINT NOT NULL,
  title_vi    TEXT NOT NULL,
  title_en    TEXT NOT NULL,
  UNIQUE (level, idx)
);

CREATE TABLE exhibition_rounds (
  round_key  TEXT PRIMARY KEY,
  judged_at  TEXT NOT NULL
);

CREATE TABLE app_settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);

CREATE TABLE "items" (
  id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type     TEXT NOT NULL CHECK (type IN ('brush_skin', 'artwork_frame', 'avatar_frame', 'pattern', 'storybook_cover')),
  slug     TEXT NOT NULL UNIQUE,
  name_vi  TEXT NOT NULL,
  name_en  TEXT NOT NULL,
  price    BIGINT,
  limited  BIGINT NOT NULL DEFAULT 0,
  rank     TEXT,
  sort     BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE user_stats (
  user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  key     TEXT NOT NULL,
  value   BIGINT NOT NULL DEFAULT 0,
  PRIMARY KEY (user_id, key)
);

CREATE TABLE objects (
  id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  theme_id BIGINT NOT NULL REFERENCES themes (id) ON DELETE CASCADE,
  slug     TEXT NOT NULL,
  name_vi  TEXT NOT NULL,
  name_en  TEXT NOT NULL,
  sort     BIGINT NOT NULL DEFAULT 0,
  UNIQUE (theme_id, slug)
);

CREATE TABLE usage_log (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  artwork_id BIGINT,
  used_at    TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);

CREATE TABLE user_missions (
  user_id      BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  mission_id   BIGINT NOT NULL REFERENCES missions (id) ON DELETE CASCADE,
  completed_at TEXT NOT NULL,
  PRIMARY KEY (user_id, mission_id)
);

CREATE TABLE user_items (
  user_id     BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  item_id     BIGINT NOT NULL REFERENCES items (id) ON DELETE CASCADE,
  source      TEXT NOT NULL,   -- shop | rank
  acquired_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  PRIMARY KEY (user_id, item_id)
);

CREATE TABLE friendships (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  requester_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  addressee_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  status       TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'accepted')),
  created_at   TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  UNIQUE (requester_id, addressee_id)
);

CREATE TABLE storybooks (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  title       TEXT NOT NULL,
  share_token TEXT UNIQUE,
  completed   BIGINT NOT NULL DEFAULT 0,
  created_at  TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  updated_at  TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
, cover_style TEXT);

CREATE TABLE notifications (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  type       TEXT NOT NULL,
  data       TEXT NOT NULL DEFAULT '{}',
  read       BIGINT NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);

CREATE TABLE "payments" (
  id           TEXT PRIMARY KEY,
  user_id      BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  plan         TEXT NOT NULL CHECK (plan IN ('month', 'year')),
  provider     TEXT NOT NULL CHECK (provider IN ('paypal', 'momo', 'bank')),
  amount       DOUBLE PRECISION NOT NULL,
  currency     TEXT NOT NULL,
  status       TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'paid', 'failed')),
  provider_ref TEXT,
  mock         BIGINT NOT NULL DEFAULT 0,
  raw          TEXT,
  created_at   TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  paid_at      TEXT,
  -- Mã nội dung chuyển khoản (BTMxxxxxx) cho thanh toán QR.
  code         TEXT UNIQUE,
  -- Mã giao dịch phía cổng (SePay id, hoặc "<PayPal subscription>#<kỳ>") — chống ghi nhận trùng.
  txn_ref      TEXT UNIQUE
);

CREATE TABLE recurring (
  id           TEXT PRIMARY KEY,               -- PayPal subscription id (I-XXXX)
  user_id      BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  plan         TEXT NOT NULL CHECK (plan IN ('month', 'year')),
  status       TEXT NOT NULL DEFAULT 'pending', -- pending | active | cancelled | suspended | expired
  payment_id   TEXT,                           -- giao dịch tạo ra thuê bao
  created_at   TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  cancelled_at TEXT
, provider_plan_id TEXT);

CREATE TABLE pictures (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  object_id        BIGINT NOT NULL REFERENCES objects (id) ON DELETE CASCADE,
  slug             TEXT NOT NULL UNIQUE,
  variant_slug     TEXT NOT NULL,
  name_vi          TEXT NOT NULL,
  name_en          TEXT NOT NULL,
  variant_name_vi  TEXT NOT NULL,
  variant_name_en  TEXT NOT NULL,
  svg              TEXT NOT NULL,
  manifest         TEXT NOT NULL,      -- JSON: { palette, regions[] }
  animation        TEXT NOT NULL DEFAULT 'bounce',
  is_card          BIGINT NOT NULL DEFAULT 0,
  rarity           TEXT CHECK (rarity IN ('S', 'A', 'B', 'C')),
  sort             BIGINT NOT NULL DEFAULT 0,
  created_at       TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
, theme_sort BIGINT NOT NULL DEFAULT 1000, hidden BIGINT NOT NULL DEFAULT 0);

CREATE TABLE subscriptions (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  plan       TEXT NOT NULL CHECK (plan IN ('month', 'year')),
  starts_at  TEXT NOT NULL,
  ends_at    TEXT NOT NULL,
  payment_id TEXT REFERENCES payments (id)
, reminded_at TEXT);

CREATE TABLE artworks (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  picture_id    BIGINT NOT NULL REFERENCES pictures (id),
  mode          TEXT NOT NULL CHECK (mode IN ('template', 'free', 'arena', 'collab')),
  data          TEXT NOT NULL DEFAULT '{"fills":{},"strokes":[],"stickers":[]}',
  thumbnail     TEXT,
  status        TEXT NOT NULL DEFAULT 'in_progress' CHECK (status IN ('in_progress', 'completed')),
  counted       BIGINT NOT NULL DEFAULT 0,  -- đã tính 1 lượt tô hay chưa
  artwork_frame TEXT,
  warned_at     TEXT,
  created_at    TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  updated_at    TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  completed_at  TEXT
);

CREATE TABLE user_cards (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  picture_id  BIGINT NOT NULL REFERENCES pictures (id),
  source      TEXT NOT NULL,   -- gacha | trade | gift
  obtained_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);

CREATE TABLE gacha_pulls (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  picture_id BIGINT NOT NULL REFERENCES pictures (id),
  rarity     TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);

CREATE TABLE arena_rooms (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code         TEXT NOT NULL UNIQUE,
  type         TEXT NOT NULL CHECK (type IN ('random', 'private')),
  tier         TEXT,
  host_id      BIGINT REFERENCES users (id),
  picture_id   BIGINT REFERENCES pictures (id),
  status       TEXT NOT NULL DEFAULT 'waiting' CHECK (status IN ('waiting', 'playing', 'finished', 'cancelled')),
  duration_sec BIGINT NOT NULL,
  week         TEXT,
  started_at   TEXT,
  ends_at      TEXT,
  created_at   TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);

CREATE TABLE trades (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  from_user       BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  to_user         BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  offer_card_id   BIGINT NOT NULL REFERENCES user_cards (id),
  request_card_id BIGINT REFERENCES user_cards (id),  -- NULL = tặng
  status          TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'accepted', 'declined', 'cancelled', 'failed')),
  created_at      TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  resolved_at     TEXT
);

CREATE TABLE arena_entries (
  room_id      BIGINT NOT NULL REFERENCES arena_rooms (id) ON DELETE CASCADE,
  user_id      BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  data         TEXT,
  thumbnail    TEXT,
  submitted_at TEXT,
  elapsed_ms   BIGINT,
  scores       TEXT,
  total        DOUBLE PRECISION,
  place        BIGINT,
  flagged      BIGINT NOT NULL DEFAULT 0,
  flag_reason  TEXT,
  reward       BIGINT NOT NULL DEFAULT 0,
  PRIMARY KEY (room_id, user_id)
);

CREATE TABLE storybook_pages (
  storybook_id BIGINT NOT NULL REFERENCES storybooks (id) ON DELETE CASCADE,
  artwork_id   BIGINT NOT NULL REFERENCES artworks (id) ON DELETE CASCADE,
  position     BIGINT NOT NULL,
  caption      TEXT NOT NULL DEFAULT '',
  PRIMARY KEY (storybook_id, position)
);

CREATE TABLE exhibition_entries (
  id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  artwork_id      BIGINT NOT NULL REFERENCES artworks (id) ON DELETE CASCADE,
  user_id         BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  round_key       TEXT NOT NULL,
  board           TEXT NOT NULL CHECK (board IN ('S', 'A', 'B', 'free')),
  status          TEXT NOT NULL CHECK (status IN ('pending', 'approved', 'rejected', 'withdrawn', 'removed')),
  auto_approved   BIGINT NOT NULL DEFAULT 0,
  reject_rule     BIGINT,                 -- số điều nội quy bị vi phạm (1–8)
  hidden          BIGINT NOT NULL DEFAULT 0, -- tạm ẩn vì bị báo nhiều, chờ admin xem
  reports         BIGINT NOT NULL DEFAULT 0,
  award           BIGINT NOT NULL DEFAULT 0, -- 1 = "Tranh được yêu thích nhất bảng … tuần …"
  final_reactions TEXT,                    -- bảng cảm xúc chốt lúc 20:00 Chủ nhật (thành tích)
  notified_count  BIGINT NOT NULL DEFAULT 0,
  notified_date   TEXT,
  submitted_at    TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  reviewed_at     TEXT,
  reviewed_by     BIGINT
);

CREATE TABLE exhibition_reactions (
  entry_id   BIGINT NOT NULL REFERENCES exhibition_entries (id) ON DELETE CASCADE,
  user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  emoji      TEXT NOT NULL CHECK (emoji IN ('heart', 'cheer', 'clap', 'love', 'star')),
  created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  PRIMARY KEY (entry_id, user_id)
);

CREATE TABLE exhibition_reports (
  entry_id   BIGINT NOT NULL REFERENCES exhibition_entries (id) ON DELETE CASCADE,
  user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  PRIMARY KEY (entry_id, user_id)
);

CREATE INDEX idx_users_guardian ON users (guardian_contact);

CREATE INDEX idx_pictures_object ON pictures (object_id, is_card);

CREATE INDEX idx_artworks_user ON artworks (user_id, status, updated_at);

CREATE INDEX idx_usage_user ON usage_log (user_id, used_at);

CREATE INDEX idx_subs_user ON subscriptions (user_id, ends_at);

CREATE INDEX idx_user_cards_user ON user_cards (user_id);

CREATE INDEX idx_trades_users ON trades (from_user, to_user, status);

CREATE INDEX idx_notifications_user ON notifications (user_id, read);

CREATE UNIQUE INDEX idx_exhibit_artwork_once ON exhibition_entries (artwork_id) WHERE status IN ('pending', 'approved', 'removed');

CREATE INDEX idx_exhibit_round ON exhibition_entries (round_key, board, status);

CREATE INDEX idx_exhibit_user ON exhibition_entries (user_id, submitted_at);

CREATE INDEX idx_payments_user ON payments (user_id, created_at);

CREATE INDEX idx_recurring_user ON recurring (user_id, status);

CREATE UNIQUE INDEX idx_users_username_lower ON users (LOWER(username));
